#!/usr/bin/env bash

set -euo pipefail

# 这条 wrapper 固定 Suite D 的 24 核 AI-off flamegraph 口径。
# 它只负责给主扩展曲线提供“热点解释图”，所以必须和 24 核 T2 主曲线共用同一套 sender/backend 拓扑与 AI-off 条件。

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../../.." && pwd)"

PROFILE="${SUITE_D_PROFILE:-end}"
RESULT_ROOT="${SUITE_D_RESULT_ROOT:-/tmp/suite_d_flamegraph_24c}"
PORT="${SUITE_D_PORT:-18400}"
SERVER_CPUSET="${SUITE_D_SERVER_CPUSET:-4-23}"
WRK_CPUSET="${SUITE_D_WRK_CPUSET:-0-3}"
SERVER_IO_THREADS="${SUITE_D_SERVER_IO_THREADS:-6}"
DISPATCH_WORKER_THREADS="${SUITE_D_DISPATCH_WORKER_THREADS:-4}"
WORKER_THREADS="${SUITE_D_WORKER_THREADS:-32}"
WORKER_QUEUE_SIZE="${SUITE_D_WORKER_QUEUE_SIZE:-8192}"
TRACE_ACTIVE_SESSION_LIMIT="${SUITE_D_TRACE_ACTIVE_SESSION_LIMIT:-2048}"
TRACE_BUFFERED_SPAN_LIMIT="${SUITE_D_TRACE_BUFFERED_SPAN_LIMIT:-16384}"
TRACE_MAX_DISPATCH_PER_TICK="${SUITE_D_TRACE_MAX_DISPATCH_PER_TICK:-64}"
TRACE_LIFECYCLE_PROFILE="${SUITE_D_TRACE_LIFECYCLE_PROFILE:-protected}"
WRK_THREADS="${SUITE_D_WRK_THREADS:-4}"
CONNECTIONS="${SUITE_D_CONNECTIONS:-120}"
WARMUP_CONNECTIONS="${SUITE_D_WARMUP_CONNECTIONS:-40}"
WARMUP_DURATION="${SUITE_D_WARMUP_DURATION:-3s}"
DURATION="${SUITE_D_DURATION:-15s}"
WRK_SCRIPT="${ROOT_DIR}/server/tests/benchmark/suite_d/trace_model_suite_d.lua"

# 这里显式关闭 AI / webhook / proxy 自动拉起，确保 flamegraph 只解释后端主链路。
DISABLE_AI=1 \
DISABLE_WEBHOOK=1 \
NO_AUTO_START_PROXY=1 \
RESULT_ROOT="${RESULT_ROOT}" \
PORT="${PORT}" \
SERVER_CPUSET="${SERVER_CPUSET}" \
WRK_CPUSET="${WRK_CPUSET}" \
SERVER_IO_THREADS="${SERVER_IO_THREADS}" \
DISPATCH_WORKER_THREADS="${DISPATCH_WORKER_THREADS}" \
WORKER_THREADS="${WORKER_THREADS}" \
WORKER_QUEUE_SIZE="${WORKER_QUEUE_SIZE}" \
TRACE_ACTIVE_SESSION_LIMIT="${TRACE_ACTIVE_SESSION_LIMIT}" \
TRACE_BUFFERED_SPAN_LIMIT="${TRACE_BUFFERED_SPAN_LIMIT}" \
TRACE_MAX_DISPATCH_PER_TICK="${TRACE_MAX_DISPATCH_PER_TICK}" \
TRACE_LIFECYCLE_PROFILE="${TRACE_LIFECYCLE_PROFILE}" \
WRK_THREADS="${WRK_THREADS}" \
CONNECTIONS="${CONNECTIONS}" \
WARMUP_CONNECTIONS="${WARMUP_CONNECTIONS}" \
WARMUP_DURATION="${WARMUP_DURATION}" \
DURATION="${DURATION}" \
WRK_SCRIPT="${WRK_SCRIPT}" \
exec "${ROOT_DIR}/server/tests/benchmark/suite_d/run_flamegraph.sh" "${PROFILE}"
